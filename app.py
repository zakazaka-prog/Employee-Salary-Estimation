"""Streamlit web interface for Employee Salary Estimation."""
from pathlib import Path
import joblib
import pandas as pd
import streamlit as st

ROOT = Path(__file__).parent
MODEL_PATH = ROOT / "model" / "salary_model.joblib"
DATA_PATH = ROOT / "dataset" / "employee_salary.csv"

st.set_page_config(page_title="Employee Salary Estimation", page_icon="💼", layout="centered")
st.title("💼 Employee Salary Estimation")
st.write(
    "Estimate an employee's annual salary using job role, years of experience, "
    "and weekly working hours."
)
st.info(
    "Academic demonstration only: the included dataset is synthetic. "
    "Predictions are not verified market salary benchmarks."
)

if not MODEL_PATH.exists():
    st.error("Trained model not found. Run `python train_model.py` in the project folder.")
    st.stop()

model = joblib.load(MODEL_PATH)

if DATA_PATH.exists():
    roles = sorted(pd.read_csv(DATA_PATH)["Job_Role"].dropna().unique().tolist())
else:
    roles = [
        "Data Analyst", "Data Scientist", "Manager",
        "Machine Learning Engineer", "Network Engineer",
        "Software Engineer", "UI/UX Designer", "Web Developer"
    ]

with st.form("salary_form"):
    role = st.selectbox("Job role", roles)
    experience = st.slider("Work experience (years)", min_value=0, max_value=20, value=2)
    hours = st.slider("Working hours per week", min_value=30, max_value=60, value=40)
    submitted = st.form_submit_button("Estimate salary", type="primary")

if submitted:
    employee = pd.DataFrame([{
        "Job_Role": role,
        "Experience_Years": experience,
        "Working_Hours_Per_Week": hours,
    }])
    estimate = float(model.predict(employee)[0])
    st.subheader("Estimated annual salary")
    st.success(f"₹ {estimate:,.0f}")
    st.caption("Estimate generated by the trained Random Forest Regression model.")
